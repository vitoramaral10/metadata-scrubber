def test_gif_animado_mantem_loop():
    # Cores distintas de verdade: frames identicos seriam colapsados num so
    # pelo proprio Pillow, e o teste passaria a nao testar nada.
    cores = [(255, 0, 0), (0, 255, 0), (0, 0, 255)]
    frames = [Image.new("RGB", (16, 16), c).convert("P") for c in cores]
    buffer = io.BytesIO()
    frames[0].save(
        buffer, format="GIF", save_all=True, append_images=frames[1:], loop=0, duration=100
    )
    original = buffer.getvalue()

    cleaned, _ = scrub_bytes(original)

    assert b"NETSCAPE2.0" in cleaned
    with Image.open(io.BytesIO(cleaned)) as image:
        assert image.n_frames == 3


